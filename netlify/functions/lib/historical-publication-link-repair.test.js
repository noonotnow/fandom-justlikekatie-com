import assert from "node:assert/strict";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { getStore } from "@netlify/blobs";
import { BlobsServer } from "@netlify/blobs/server";
import publicRecords from "../public-records.js";
import publicEditions from "../public-editions.js";
import { createPublicSitemapHandler } from "../public-sitemap.js";
import {
  gridManifestKey,
  isGridManifest,
  isIndexablePublicationManifest,
  publicationManifestCatalogKey,
  PUBLICATION_RELEASE_DATES_KEY,
  publicationReleaseReceiptKey,
  repairPublicationManifestPublicRecords,
} from "./publication-manifest.js";
import {
  HISTORICAL_PUBLICATION_APPROVALS,
  historicalPublicationFingerprint,
} from "./historical-publication-approvals.js";
import { manifestFromEvidence, reviewedEvidence } from "./test-fixtures/reviewed-historical-publications.js";

const evidence = reviewedEvidence[0];
const date = evidence.publicationDate;
const slug = evidence.actor.nameEn.toLowerCase().replaceAll(" ", "-");
const actorPath = `/vibe-atlas/actors/${slug}/`;
const editionPath = `/vibe-atlas/editions/${date}/${slug}/`;
const origin = "https://fandom.justlikekatie.com";
const key = gridManifestKey(date);
const request = path => new Request(origin + path);
const escapeHtml = value => value.replaceAll("&", "&amp;").replaceAll("<", "&lt;")
  .replaceAll(">", "&gt;").replaceAll('"', "&quot;").replaceAll("'", "&#39;");

function approvedManifest() {
  const manifest = manifestFromEvidence(evidence);
  assert.equal(isGridManifest(manifest), true);
  assert.equal(isIndexablePublicationManifest(manifest), true);
  assert.equal(historicalPublicationFingerprint(manifest), HISTORICAL_PUBLICATION_APPROVALS[date]);
  return manifest;
}

async function harness(t) {
  const directory = await mkdtemp(join(tmpdir(), "historical-link-repair-"));
  const server = new BlobsServer({ directory });
  t.after(async () => {
    await server.stop();
    await rm(directory, { recursive: true, force: true });
  });
  const { address } = await server.start();
  const store = getStore({
    edgeURL: address, uncachedEdgeURL: address,
    name: "historical-link-repair", siteID: "test-site", token: "test-token",
  });
  await store.setJSON(key, approvedManifest());
  await store.setJSON(publicationManifestCatalogKey(), {
    schemaVersion: 1, catalogVersion: "v1",
    kind: "vibe-atlas-publication-manifest-catalog", dates: [date],
  });
  // Pre-existing release evidence, not generated by the public read or repair.
  await store.setJSON(PUBLICATION_RELEASE_DATES_KEY, {
    schemaVersion: 1, kind: "vibe-atlas-released-dates",
    verifiedBaseline: true, dates: [date],
  });
  await store.setJSON(publicationReleaseReceiptKey(date), {
    schemaVersion: 1, kind: "vibe-atlas-release-receipt", date,
  });
  const context = { blobs: { getStore: () => store } };
  const sitemap = createPublicSitemapHandler({
    // Released Collector packs are unrelated to this historical edition.
    buildReleaseCatalog: async () => ({ complete: true, indexingComplete: true, packs: [] }),
    logError: error => assert.fail(error),
  });
  const snapshot = async () => {
    const pages = await Promise.all(
      [actorPath, editionPath, `/zh-cn${actorPath}`, `/zh-cn${editionPath}`]
        .map(async path => {
          const response = await publicRecords(request(path), context);
          return { status: response.status, body: await response.text() };
        }),
    );
    const edition = await publicEditions(request(`/.netlify/functions/public-editions?date=${date}&actor=${slug}`), context);
    const directory = await publicEditions(request("/.netlify/functions/public-editions"), context);
    return {
      pages,
      edition: { status: edition.status, body: await edition.json() },
      directory: { status: directory.status, body: await directory.json() },
      sitemap: await sitemap(request("/sitemap.xml"), context),
    };
  };
  return { store, snapshot };
}

function assertPublic(snapshot) {
  assert.deepEqual(snapshot.pages.map(page => page.status), [200, 200, 200, 200]);
  assert.equal(snapshot.edition.status, 200);
  assert.equal(snapshot.directory.status, 200);
  assert.equal(snapshot.directory.body.actors.length, 1);
  assert.deepEqual(snapshot.directory.body.actors[0].editions, [
    { date, path: editionPath, canonical: origin + editionPath },
  ]);
  const preview = snapshot.edition.body;
  assert.equal(preview.vibe.label, evidence.vibe.label);
  assert.equal(preview.vibe.labelEn, evidence.vibe.labelEn);
  assert.equal(preview.vibe.subtitle, evidence.vibe.subtitle);
  assert.equal(preview.vibe.subtitleEn, evidence.vibe.subtitleEn);
  assert.equal(preview.vibe.copy, evidence.vibe.subtitleEn);
  assert.equal(preview.previews.length, 9);
  assert.deepEqual(preview.previews.map(card => ({
    position: card.position, deliveryUrl: card.deliveryUrl,
    thumbnailUrl: card.thumbnailUrl, mimeType: card.mimeType, dimensions: card.dimensions,
  })), evidence.cards.map(({ position, media }) => ({
    position, deliveryUrl: media.deliveryUrl, thumbnailUrl: media.thumbnailUrl,
    mimeType: media.mimeType, dimensions: media.dimensions,
  })));
  for (const [index, locale] of [[1, "en"], [3, "zh-CN"]]) {
    const html = snapshot.pages[index].body;
    assert.ok(html.includes(`<html lang="${locale}">`));
    assert.ok(html.includes('content="index,follow,max-image-preview:large"'));
    const copyFields = locale === "en" ? ["labelEn", "subtitleEn"]
      : ["label", "labelEn", "subtitle", "subtitleEn"];
    for (const field of copyFields) assert.ok(html.includes(escapeHtml(evidence.vibe[field])), field);
    assert.deepEqual([...html.matchAll(/<img src="([^"]+)"/g)].map(match => match[1]),
      evidence.cards.map(card => escapeHtml(card.media.thumbnailUrl)));
  }
  assert.equal(snapshot.sitemap.headers["X-Public-Sitemap-Inventory"], "complete");
  for (const path of [actorPath, editionPath]) {
    assert.equal(snapshot.sitemap.body.split(`<loc>${origin}${path}</loc>`).length - 1, 1);
    assert.ok(snapshot.sitemap.body.includes(`hreflang="zh-CN" href="${origin}/zh-cn${path}"`));
  }
}

function assertClosed(snapshot, malformed) {
  assert.deepEqual(snapshot.pages.map(page => page.status), Array(4).fill(malformed ? 503 : 404));
  for (const page of snapshot.pages) {
    assert.ok(page.body.includes('content="noindex,follow"'));
    for (const card of evidence.cards) assert.ok(!page.body.includes(card.media.deliveryUrl));
  }
  assert.equal(snapshot.edition.status, malformed ? 503 : 404);
  assert.equal(snapshot.directory.status, malformed ? 503 : 200);
  if (!malformed) assert.deepEqual(snapshot.directory.body.actors, []);
  assert.equal(snapshot.sitemap.headers["X-Public-Sitemap-Inventory"],
    malformed ? "publication-incomplete" : "complete");
  assert.ok(!snapshot.sitemap.body.includes(origin + actorPath));
  assert.ok(!snapshot.sitemap.body.includes(origin + editionPath));
}

test("stored metadata-only historical link repair preserves EN/ZH pages, nine MEDIA, directory and sitemap", async t => {
  const { store, snapshot } = await harness(t);
  const before = await snapshot();
  assertPublic(before);
  const original = await store.get(key, { type: "json", consistency: "strong" });
  assert.equal(Object.hasOwn(original, "publicRecord"), false);
  const result = await repairPublicationManifestPublicRecords(store);
  assert.equal(result.repaired, 1);
  assert.equal(result.cataloged, 0);
  const repaired = await store.get(key, { type: "json", consistency: "strong" });
  assert.deepEqual(repaired.publicRecord, { actorPath, editionPath });
  const { publicRecord: _publicRecord, ...unchanged } = repaired;
  assert.deepEqual(unchanged, original);
  assert.deepEqual(repaired.cards.map(card => card.media), evidence.cards.map(card => card.media));
  assert.equal(historicalPublicationFingerprint(repaired), HISTORICAL_PUBLICATION_APPROVALS[date]);
  const after = await snapshot();
  assertPublic(after);
  assert.deepEqual(after, before);
  assert.equal((await repairPublicationManifestPublicRecords(store)).repaired, 0);

  // An existing but broken annotation is also repairable without re-approval.
  await store.setJSON(key, {
    ...repaired,
    publicRecord: { actorPath: "/vibe-atlas/actors/wrong-actor/", editionPath },
  });
  assertClosed(await snapshot(), true);
  assert.equal((await repairPublicationManifestPublicRecords(store)).repaired, 1);
  assert.deepEqual(await store.get(key, { type: "json", consistency: "strong" }), repaired);
  assert.deepEqual(await snapshot(), before);
});

test("a malformed repair write fails verification and all public surfaces close despite an unchanged approval fingerprint", async t => {
  const { store, snapshot } = await harness(t);
  assertPublic(await snapshot());
  const setJSON = store.setJSON.bind(store);
  let injected = false;
  store.setJSON = async (writeKey, value, options) => {
    if (writeKey === key && options?.onlyIfMatch) {
      injected = true;
      value = { ...value, publicRecord: { ...value.publicRecord, editionPath: "/admin/private/" } };
    }
    return setJSON(writeKey, value, options);
  };
  await assert.rejects(repairPublicationManifestPublicRecords(store), /repair could not be verified/);
  assert.equal(injected, true);
  const malformed = await store.get(key, { type: "json", consistency: "strong" });
  assert.equal(historicalPublicationFingerprint(malformed), HISTORICAL_PUBLICATION_APPROVALS[date]);
  assert.equal(isGridManifest(malformed), false);
  assert.equal(isIndexablePublicationManifest(malformed), false);
  assertClosed(await snapshot(), true);
});

test("link repair never carries historical approval across bilingual copy or any of the nine MEDIA substitutions", async t => {
  const { store, snapshot } = await harness(t);
  assertPublic(await snapshot());
  const substitutions = [
    ["English copy", manifest => {
      manifest.vibe.supportingCopyEn = "Unreviewed replacement copy that exceeds the normal public editorial minimum.";
    }],
    ["Chinese copy", manifest => { manifest.vibe.subtitle = "未经审核的替换文案"; }],
    ...Array.from({ length: 9 }, (_, position) => [`MEDIA position ${position}`, manifest => {
      // A well-formed MEDIA reference from another fixed edition, retaining
      // this edition's valid association. Only the historical pin rejects it.
      const association = manifest.cards[position].media.association;
      manifest.cards[position].media = {
        ...structuredClone(reviewedEvidence[1].cards[position].media), association,
      };
    }]),
    ["copy and MEDIA together", manifest => {
      manifest.vibe.supportingCopyEn = "Unreviewed replacement copy that exceeds the normal public editorial minimum.";
      manifest.cards[0].media.assetId = "00000000-0000-4000-8000-000000000001";
    }],
  ];
  for (const [label, substitute] of substitutions) {
    await t.test(label, async () => {
      const manifest = approvedManifest();
      substitute(manifest);
      assert.equal(isGridManifest(manifest), true);
      await store.setJSON(key, manifest);
      const result = await repairPublicationManifestPublicRecords(store);
      assert.equal(result.repaired, 1);
      const repaired = await store.get(key, { type: "json", consistency: "strong" });
      assert.deepEqual(repaired.publicRecord, { actorPath, editionPath });
      const { publicRecord: _publicRecord, ...unchanged } = repaired;
      assert.deepEqual(unchanged, manifest);
      assert.equal(isGridManifest(repaired), true);
      assert.notEqual(historicalPublicationFingerprint(repaired), HISTORICAL_PUBLICATION_APPROVALS[date]);
      assert.equal(isIndexablePublicationManifest(repaired), false);
      assertClosed(await snapshot(), false);
    });
  }
});
